/** 编辑器允许的总时长范围（秒）：5～30 分钟。 */
export const USER_PLAN_MIN_SECONDS = 5 * 60;
export const USER_PLAN_MAX_SECONDS = 30 * 60;

const PLAN_ID_PATTERN = /^[a-z0-9][a-z0-9-]{1,48}$/;

function clampInt(value, min, max, fallback) {
  const number = Math.round(Number(value));
  if (!Number.isFinite(number)) return fallback;
  return Math.min(max, Math.max(min, number));
}

function textOf(value, maxLength, fallback = '') {
  const text = String(value ?? '').trim();
  return (text || fallback).slice(0, maxLength);
}

/** 生成一个不会和现有计划撞车的新 id。 */
function makePlanId(knownIds) {
  const known = new Set(knownIds);
  for (let attempt = 0; attempt < 20; attempt += 1) {
    const id = `my-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 6)}`;
    if (!known.has(id)) return id;
  }
  return `my-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
}

/**
 * 把设置页编辑器提交上来的对象规整成一套合法计划。
 * 不合法时抛出中文错误（会直接显示给用户）。
 *
 * @param {object} input 编辑器提交的计划
 * @param {object} [options]
 * @param {string[]} [options.knownIds] 已有计划 id，用来避免生成重复 id
 * @param {boolean} [options.allowGenerateId] 没有 id 时是否自动生成（新建计划用）
 */
export function normalizeUserPlan(input, options = {}) {
  if (!input || typeof input !== 'object') throw new Error('计划内容为空');

  const knownIds = options.knownIds ?? [];
  const allowGenerateId = options.allowGenerateId !== false;
  let id = String(input.id ?? '').trim();
  if (!id) {
    if (!allowGenerateId) throw new Error('计划缺少 id');
    id = makePlanId(knownIds);
  }
  if (!PLAN_ID_PATTERN.test(id)) throw new Error('计划 id 只能用小写字母、数字和短横线');

  const emoji = textOf(input.emoji, 24, '🧘');
  const title = textOf(input.title, 40);
  if (!title) throw new Error('计划名字不能为空');
  const summary = textOf(input.summary, 80);
  if (!summary) throw new Error('计划概要不能为空');
  const intensity = textOf(input.intensity, 12, '轻松');
  const focus = textOf(input.focus, 20, '全身');
  const category = textOf(input.category, 12, '运动');
  const prepareSeconds = clampInt(input.prepareSeconds, 3, 30, 10);

  if (!Array.isArray(input.steps) || input.steps.length === 0) {
    throw new Error('至少要有一个动作步骤');
  }
  if (input.steps.length > 80) throw new Error('步骤太多了（最多 80 步）');

  const steps = input.steps.map((step, index) => {
    const label = `第 ${index + 1} 步`;
    if (!step || typeof step !== 'object') throw new Error(`${label}内容为空`);

    const kind = step.kind === 'rest' ? 'rest' : 'reps';
    const name = textOf(step.name, 40);
    if (!name) throw new Error(`${label}缺少动作名`);
    const cue = textOf(step.cue, 200);
    const seconds = Math.round(Number(step.seconds));
    if (!Number.isFinite(seconds) || seconds < 1 || seconds > 600) {
      throw new Error(`${label}的秒数要在 1～600 之间`);
    }

    if (kind === 'rest') return { kind, name, seconds, cue };

    const target = Math.round(Number(step.target));
    if (!Number.isFinite(target) || target < 1 || target > 9999) {
      throw new Error(`${label}「${name}」的次数要在 1～9999 之间`);
    }
    const unit = textOf(step.unit, 8, '个');
    const normalized = { kind, name, target, unit, seconds, cue };

    if (step.set !== undefined && step.set !== null && step.set !== '') {
      const set = clampInt(step.set, 1, 30, 0);
      if (!set) throw new Error(`${label}的组号要在 1～30 之间`);
      normalized.set = set;
    }
    if (step.sets !== undefined && step.sets !== null && step.sets !== '') {
      const sets = clampInt(step.sets, 1, 30, 0);
      if (!sets) throw new Error(`${label}的组数要在 1～30 之间`);
      normalized.sets = sets;
    }
    if (normalized.set && normalized.sets && normalized.set > normalized.sets) {
      throw new Error(`${label}的组号不能大于组数`);
    }
    const group = textOf(step.group, 40);
    if (group) normalized.group = group;
    return normalized;
  });

  const totalSeconds =
    prepareSeconds + steps.reduce((sum, step) => sum + Number(step.seconds), 0);
  // 短运动计划是 3～5 分钟的小休息，普通计划还是 5～30 分钟，按分类分档校验。
  const isShort = category === PLAN_CATEGORY.SHORT;
  const minSeconds = isShort ? SHORT_PLAN_MIN_SECONDS : USER_PLAN_MIN_SECONDS;
  const maxSeconds = isShort ? SHORT_PLAN_MAX_SECONDS : USER_PLAN_MAX_SECONDS;
  if (totalSeconds < minSeconds || totalSeconds > maxSeconds) {
    const minutes = (totalSeconds / 60).toFixed(1);
    if (isShort) {
      throw new Error(`总时长 ${minutes} 分钟，短运动计划需要在 3～5 分钟之间（含准备 10 秒）`);
    }
    throw new Error(`总时长 ${minutes} 分钟，需要在 5～30 分钟之间（12～15 分钟最合适）`);
  }

  return {
    id,
    emoji,
    title,
    summary,
    intensity,
    focus,
    category,
    prepareSeconds,
    totalSeconds,
    steps
  };
}
