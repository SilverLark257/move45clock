/**
 * 「随机动起来~」计划库
 * ============================================================================
 *
 * 设计原则：
 *   · 前 12 套是运动计划，所有动作都能**坐着或站着**完成，不含跳跃、不含垫上动作；
 *   · 接着 4 套是「家务休闲」：擦桌子、拖地、整理衣服、洗衣，把轻家务变成休息；
 *   · 最后 6 套是「短运动」：3～5 分钟的小锻炼，用在「短短短长」节奏里当短休息；
 *   · 每套 12～15 分钟（短运动除外），含 10 秒准备、动作、组间休息、最后拉伸/呼吸；
 *   · 动作有次数/秒数、组数、详细提示，弹窗按时间线倒数。
 *
 * ── 想自己加计划 / 改计划？────────────────────────────────────────────────
 *  1. 复制一个 plan({...}) 块，改 id（不能重复）、emoji、title、summary；
 *  2. steps 里每一步：
 *       reps(名字, 次数, 单位, 持续秒数, 提示, { set, sets, group })
 *       rest(名字, 持续秒数, 提示)
 *     持续秒数要和你写的次数匹配（比如 100 个踏步 ≈ 100 秒）；
 *  3. totalSeconds 会自动算出来（准备 10 秒 + 所有步骤）；
 *  4. 保存后完全重启 DSH，弹窗和设置页就会看到新计划。
 *
 * 以后会做"可视化编辑器"；现在的入口就是这份文件 + 设置页里的计划库列表。
 */

/** 一个"次数型"动作：target 个 / 秒数内完成，弹窗会把数字从 target 倒数到 0。 */
function reps(name, target, unit, seconds, cue, extra = {}) {
  return { kind: 'reps', name, target, unit, seconds, cue, ...extra };
}

/** 一个"休息/过渡"动作：只倒数秒数。 */
function rest(name, seconds, cue) {
  return { kind: 'rest', name, seconds, cue };
}

/** 组装一套计划，自动算总时长（准备 + 所有步骤）。 */
function plan(data) {
  const prepareSeconds = data.prepareSeconds ?? 10;
  const totalSeconds = prepareSeconds + data.steps.reduce((sum, step) => sum + step.seconds, 0);
  return { ...data, prepareSeconds, totalSeconds };
}

// ── 计划分类 / 计划模式（v1.7.0）───────────────────────────────────────────
// 用户第 3 条：设置页让用户选「你偏爱的计划类」。三种模式决定休息时从哪些计划里抽：
//   exercise   = 只抽纯运动（12 套 12～15 分钟，不含家务、不含短运动）
//   mixed      = 运动 + 家务休闲（v1.6.0 的老行为）
//   short-long = 短短短长：3 次短运动（3～5 分钟）后跟 1 次长运动（12～15 分钟）
// 默认 short-long 是用户第 2 条明确要「实行」的节奏，老设置文件没有该字段时按默认迁移。
export const PLAN_MODES = ['exercise', 'mixed', 'short-long'];
export const DEFAULT_PLAN_MODE = 'short-long';
export const PLAN_CATEGORY = { EXERCISE: '运动', CHORE: '家务休闲', SHORT: '短运动' };

/** 计划属于哪一类：exercise / chore / short（没写 category 的老计划当运动）。 */
export function planKind(plan) {
  const category = plan?.category;
  if (category === PLAN_CATEGORY.SHORT) return 'short';
  if (category === PLAN_CATEGORY.CHORE) return 'chore';
  return 'exercise';
}

